/**
 * Reviewed symptom sets.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * CLINICAL REVIEW REQUIRED
 * Every set, question, red flag and category in this file is authored content
 * that must be signed off by a named clinician before this is used with real
 * patients. `reviewStatus` is therefore `needs_clinician_review` on every
 * record: nothing here claims to be approved, because nothing here has been.
 * ─────────────────────────────────────────────────────────────────────────────
 *
 * The architecture this file exists to enforce:
 *
 *     FREE TEXT → CLASSIFY → PREDEFINED SET → QUESTIONS → RED FLAGS → SUMMARY
 *
 * Free text never generates a question. It only picks which set is opened, and
 * the set is closed, versioned, reviewable data. A model is never asked what to
 * ask, and a model is never asked whether something is urgent.
 *
 * Adding a set means: add keywords, add questions, add red flags, add reviewed
 * categories. Nothing else in the codebase needs to change.
 */
