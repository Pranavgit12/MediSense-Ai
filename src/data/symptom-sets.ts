/** Every record in this file carries this until a clinician signs it off. */
const NEEDS_REVIEW = 'needs_clinician_review' as const;

// ── Question authoring helper ────────────────────────────────────────────────
//
// Written in a deliberately terse form so a reviewer can read a whole set on
// one screen. The shape it produces is the real `SymptomQuestion`, so the same
// object can be validated, persisted and rendered.

type Q = Pick<
  SymptomQuestion,
  'key' | 'prompt' | 'kind' | 'priority' | 'safetyCritical'
> &
  Partial<Omit<SymptomQuestion, 'key' | 'prompt' | 'kind' | 'priority' | 'safetyCritical'>>;

function q(setId: string, spec: Q): SymptomQuestion {
  return {
    id: `${setId}_${spec.key}`,
    key: spec.key,
    prompt: spec.prompt,
    helpText: spec.helpText ?? null,
    kind: spec.kind,
    options: spec.options ?? [],
    dependsOnKey: spec.dependsOnKey ?? null,
    dependsOnValues: spec.dependsOnValues ?? [],
    skipIfKey: spec.skipIfKey ?? null,
    skipIfValues: spec.skipIfValues ?? [],
    priority: spec.priority,
    targetSymptoms: spec.targetSymptoms ?? [setId],
    safetyCritical: spec.safetyCritical,
    min: spec.min ?? null,
    max: spec.max ?? null,
    unit: spec.unit ?? null,
    reviewerNote: spec.reviewerNote ?? null,
    version: '1.0.0',
    symptomSet: setId,
  };
}

/** Shorthand for a yes/no safety question. */
const yesNo = (value: string, label?: string) => ({ value, label: label ?? 'Yes' });

function rule(
  spec: Omit<RedFlagRule, 'reviewStatus' | 'version' | 'reviewerNote'> & {
    version?: string;
    reviewerNote?: string | null;
  },
): RedFlagRule {
  return {
    ...spec,
    reviewStatus: NEEDS_REVIEW,
    version: spec.version ?? '1.0.0',
    // An unreviewed rule that carries no note is a normal state, not a defect:
    // the review workflow is what fills this in once a clinician signs off.
    reviewerNote: spec.reviewerNote ?? null,
  };
}

function cat(
  id: string,
  label: string,
  system: MedicalCategory['system'],
  hedgedNote: string,
  sourceId: string | null = 'medlineplus-nlm',
): MedicalCategory {
  return { id, label, system, hedgedNote, sourceId };
}

