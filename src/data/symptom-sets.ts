const BY_ID = new Map<string, SymptomSet>(SYMPTOM_SETS.map((s) => [s.id, s]));

export function symptomSet(id: string): SymptomSet | undefined {
  return BY_ID.get(id);
}

export function symptomSetName(id: string): string {
  return BY_ID.get(id)?.name ?? id.replace(/_/g, ' ');
}

/** Every question in a set, prefixed by the shared baseline. */
export function questionsForSet(setId: string): SymptomQuestion[] {
  const set = BY_ID.get(setId);
  if (!set) return [];
  return [...SHARED_QUESTIONS, ...set.questions];
}

/**
 * Match a complaint to a small number of authored question sets. Text can
 * select a set, but never invent a question or diagnose a condition.
 */
export function matchSymptomSets(text: string, maxSets = 3): string[] {
  const lower = text.toLocaleLowerCase();
  const matches: { id: string; score: number }[] = [];

  for (const candidate of SYMPTOM_SETS) {
    let score = 0;
    for (const keyword of candidate.keywords) {
      const escaped = keyword.toLocaleLowerCase().replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      const expression = new RegExp(`(^|[^a-z0-9])${escaped}(?=$|[^a-z0-9])`, 'g');
      for (const match of lower.matchAll(expression)) {
        const start = match.index ?? 0;
        const prefix = lower.slice(Math.max(0, start - 48), start);
        const clause = prefix.split(/[,;.!?\n]|\bbut\b|\bhowever\b/).pop() ?? '';
        if (/\b(no|not|never|without|deny|denies|haven't|hasn't|don't|doesn't|didn't)\b/.test(clause)) continue;
        score = Math.max(score, keyword.length);
      }
    }
    if (score > 0) matches.push({ id: candidate.id, score });
  }

  const ordered = matches.sort((a, b) => b.score - a.score || a.id.localeCompare(b.id));
  const chosen = new Set(ordered.slice(0, maxSets).map((match) => match.id));
  for (const id of [...chosen]) {
    for (const opened of BY_ID.get(id)?.opensSets ?? []) {
      if (chosen.size >= maxSets) break;
      chosen.add(opened);
    }
  }
  return [...chosen];
}

